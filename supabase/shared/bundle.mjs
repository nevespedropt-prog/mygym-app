// Packs the emails, the forms and the validator into ONE file an Edge Function can import (Edge Functions deploy one folder each).
// Usage: node supabase/shared/bundle.mjs   ->  writes functions/<name>/lib.js for every function in TARGETS.
// Each module is wrapped so names never clash. Only plain `import X from`, `import { a, b } from`, `export const|function`, `export default` are supported.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve, basename } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const TARGETS = ["submit-form", "send-email", "marketing-consent"];
const ONLY = { "marketing-consent": ["shared/tokens.mjs"] };
const MODULES = ["email-templates/templates.mjs", "email-templates/settings.mjs", "email-templates/render.mjs", "forms/forms.mjs", "shared/validate.mjs", "shared/tokens.mjs"];
const id = (p) => "m_" + basename(p, ".mjs").replace(/\W/g, "_");

function wrap(path) {
  let src = readFileSync(resolve(root, path), "utf8");
  const exportsList = [];
  src = src.replace(/^import\s+(\w+)\s+from\s+"\.\/(.+?)\.mjs";?$/gm, (_m, name, file) => `const ${name} = ${id(file)}.default;`);
  src = src.replace(/^import\s+\{([^}]+)\}\s+from\s+"\.\/(.+?)\.mjs";?$/gm, (_m, names, file) => `const {${names}} = ${id(file)};`);
  src = src.replace(/^export\s+default\s+(\w+);?$/gm, (_m, n) => { exportsList.push(`default: ${n}`); return ""; });
  src = src.replace(/^export\s+(const|function|async function)\s+(\w+)/gm, (_m, kind, n) => { exportsList.push(n); return `${kind} ${n}`; });
  if (/^import\s|^export\s/m.test(src)) throw new Error("Unsupported import/export syntax in " + path);
  return `const ${id(path)} = (() => {\n${src}\nreturn { ${exportsList.join(", ")} };\n})();\n`;
}

const wrapped = Object.fromEntries(MODULES.map((m) => [m, wrap(m)]));
const tokensOnly = "// GENERATED by supabase/shared/bundle.mjs. Do not edit.\n" + wrapped["shared/tokens.mjs"] + "export const checkToken = m_tokens.checkToken;\nexport const makeToken = m_tokens.makeToken;\n";
const out = "// GENERATED by supabase/shared/bundle.mjs. Do not edit: change the source files and run the bundler again.\n" + MODULES.map((m) => wrapped[m]).join("\n") +
  "\nexport const render = m_render.render;\nexport const templates = m_render.templates;\nexport const requiredVars = m_render.requiredVars;\nexport const GLOBALS = m_render.GLOBALS;\nexport const forms = m_forms.default;\nexport const validate = m_validate.validate;\nexport const SETTINGS = m_settings.SETTINGS;\nexport const makeToken = m_tokens.makeToken;\nexport const checkToken = m_tokens.checkToken;\n";
for (const t of TARGETS) {
  try { writeFileSync(resolve(root, "functions", t, "lib.js"), t in ONLY ? tokensOnly : out); console.log("wrote functions/" + t + "/lib.js"); }
  catch (e) { console.log("skipped " + t + " (folder not there yet)"); }
}
export { out as bundleText };
